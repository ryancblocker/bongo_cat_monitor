#!/usr/bin/env python3
"""Generate the pixel fonts for Bongo Cat (LovyanGFX / TFT_eSPI "VLW" format).

    python3 -m pip install freetype-py
    ../.venv/bin/python tools/make_fonts.py   (from firmware/)

Writes src/fonts.h (declarations) and src/fonts.cpp (data). Only needed when changing font sizes; the output is committed.
"""
import os, struct
import freetype

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASCII = [chr(c) for c in range(0x20, 0x7F)]
EXTRA = ["·", "–", "’", "“", "”", "…", "°"]
DIGITS = list(" 0123456789-:.")
CAPS = list(" !-0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ")

# name, ttf, pixel size, glyphs. Press Start 2P is a pixel font drawn on an 8 px grid:
# rendered 1-bit (no anti-aliasing) at 8 and 16 px it stays perfectly crisp.
PIXEL = ASCII + ["°", "♥", "▼", "▶", "◀", "·", "…"]
FONTS = [
    ("PX8", "PressStart2P-Regular.ttf", 8, PIXEL),
    ("PX16", "PressStart2P-Regular.ttf", 16, PIXEL),
]


def vlw(ttf, px, chars):
    face = freetype.Face(os.path.join(ROOT, "fonts", ttf))
    face.set_pixel_sizes(0, px)
    glyphs = []
    for ch in sorted(set(chars), key=ord):
        if face.get_char_index(ch) == 0:
            continue  # not in this font
        face.load_char(ch, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_MONO)
        g = face.glyph
        bm = g.bitmap
        w, h = bm.width, bm.rows
        data = bytearray()
        for r in range(h):  # 1-bit rows -> 0/255 bytes
            row = bm.buffer[r * bm.pitch : (r + 1) * bm.pitch]
            data += bytes(255 if row[x >> 3] & (0x80 >> (x & 7)) else 0 for x in range(w))
        if ch == " ":
            w = h = 0
            data = bytearray()
        glyphs.append((ord(ch), h, w, round(g.advance.x / 64), g.bitmap_top, g.bitmap_left, bytes(data)))

    def metric(ch, f):
        face.load_char(ch, freetype.FT_LOAD_RENDER)
        return f(face.glyph)

    ascent = metric("d", lambda g: g.bitmap_top) if "d" in chars else metric("0", lambda g: g.bitmap_top)
    descent = metric("p", lambda g: g.bitmap.rows - g.bitmap_top) if "p" in chars else 0
    out = bytearray(struct.pack(">6i", len(glyphs), 11, px, 0, ascent, descent))
    for (u, h, w, adv, dy, dx, _) in glyphs:
        out += struct.pack(">7i", u, h, w, adv, dy, dx, 0)
    for g in glyphs:
        out += g[6]
    return bytes(out)


HDR = "// AUTO-GENERATED by tools/make_fonts.py from Press Start 2P (SIL Open Font License, see fonts/).\n"
decl = [HDR, "#pragma once", "#include <stdint.h>", ""]
defs = [HDR, '#include "fonts.h"', "#include <pgmspace.h>", ""]
total = 0
for name, ttf, px, chars in FONTS:
    data = vlw(ttf, px, chars)
    total += len(data)
    rows = ",\n".join(",".join("%d" % b for b in data[i:i + 40]) for i in range(0, len(data), 40))
    decl.append("extern const uint8_t %s[];  // %s %dpx" % (name, ttf[:-4], px))
    defs.append("const uint8_t %s[] PROGMEM = {\n%s\n};" % (name, rows))
    print("%-10s %-20s %2dpx %6d bytes" % (name, ttf, px, len(data)))
open(os.path.join(ROOT, "src", "fonts.h"), "w").write("\n".join(decl) + "\n")
open(os.path.join(ROOT, "src", "fonts.cpp"), "w").write("\n".join(defs) + "\n")
print("total", total, "bytes -> src/fonts.{h,cpp}")
