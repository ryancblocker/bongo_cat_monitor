"""Pack the cat layers from make_cats.py into firmware data + app preview images.

Each layer is cropped to its visible pixels and stored as a palette (<= 255 colours
+ index 0 = transparent, RGB565 + 8-bit alpha) and run-length rows of
(count, index) byte pairs, with a row-offset table so the firmware can decode just the
rows of the strip it is drawing.
"""
import os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "firmware", "src")
PREV = os.path.join(ROOT, "bongo-cat-electron", "renderer", "cats")

STYLES = ["cartoon", "pixel", "8bit"]
CATS = ["classic", "chonky", "kitten"]
COATS = ["default", "grey", "tabby"]
LAYERS = ["body", "body_twitch", "face_stock", "face_happy", "face_blink", "face_sleepy", "desk",
          "paws_up", "paws_left", "paws_right", "fx_left", "fx_right", "fx_zzz0", "fx_zzz1", "fx_zzz2"]
AW, AH = 240, 200


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def pack(img, scale):
    """-> dict(x, y, w, h, scale, pal565, alpha, rows, data) or None if empty."""
    img = img.convert("RGBA")
    # clear colour of invisible pixels so they quantise together
    px = img.load()
    for y in range(img.height):
        for x in range(img.width):
            if px[x, y][3] < 6:
                px[x, y] = (0, 0, 0, 0)
    bbox = img.getchannel("A").getbbox()
    if not bbox:
        return None
    img = img.crop(bbox)
    q = img.quantize(colors=255, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE)
    pal = q.getpalette(rawmode="RGBA")
    n = len(pal) // 4
    # remap: every (near-)transparent palette entry -> 0, the rest -> 1..
    remap, out_pal = {}, [(0, 0, 0, 0)]
    for i in range(n):
        r, g, b, a = pal[4 * i: 4 * i + 4]
        if a < 6:
            remap[i] = 0
        else:
            remap[i] = len(out_pal)
            out_pal.append((r, g, b, a))
    assert len(out_pal) <= 256, len(out_pal)
    w, h = q.size
    qd = q.load()
    data, rows = bytearray(), []
    for y in range(h):
        rows.append(len(data))
        x = 0
        while x < w:
            idx = remap[qd[x, y]]
            run = 1
            while x + run < w and run < 255 and remap[qd[x + run, y]] == idx:
                run += 1
            data += bytes((run, idx))
            x += run
    return dict(x=bbox[0], y=bbox[1], w=w, h=h, scale=scale,
                pal565=[rgb565(*c[:3]) for c in out_pal], alpha=[c[3] for c in out_pal], rows=rows, data=data)


def place(key, p):
    """Screen position inside the 240x200 cat area (8-bit cat: 192 px wide, centred, bottom-aligned)."""
    if key.startswith("8bit/"):
        ox, oy = (AW - 64 * 3) // 2, AH - 64 * 3
    else:
        ox, oy = 0, 0
    return ox + p["x"] * p["scale"], oy + p["y"] * p["scale"]


def cname(key):
    return "img_" + key.replace("/", "_").replace("-", "x")


def export(layers, compose):
    os.makedirs(SRC, exist_ok=True)
    packed = {}
    total = 0
    for key, (img, sc) in layers.items():
        p = pack(img, sc)
        if p:
            p["sx"], p["sy"] = place(key, p)
            packed[key] = p
            total += len(p["data"]) + 4 * len(p["rows"]) + 3 * len(p["pal565"])
    print("cat assets: %d images, %.0f KB" % (len(packed), total / 1024))

    with open(os.path.join(SRC, "cat_assets.cpp"), "w") as f:
        f.write("// AUTO-GENERATED by tools/make_cats.py --export. Do not edit.\n#include \"cat_assets.h\"\n\n")
        for key, p in packed.items():
            n = cname(key)
            f.write(f"// {key}\nstatic const uint16_t {n}_pal[] = {{{','.join(str(v) for v in p['pal565'])}}};\n")
            f.write(f"static const uint8_t {n}_a[] = {{{','.join(str(v) for v in p['alpha'])}}};\n")
            f.write(f"static const uint32_t {n}_rows[] = {{{','.join(str(v) for v in p['rows'])}}};\n")
            data = ",".join(str(b) for b in p["data"])
            f.write(f"static const uint8_t {n}_d[] = {{{data}}};\n")
            f.write(f"static const CatImg {n} = {{{p['sx']}, {p['sy']}, {p['w']}, {p['h']}, {p['scale']}, "
                    f"{n}_pal, {n}_a, {n}_rows, {n}_d}};\n\n")

        def lookup(style, cat, coat, layer):
            for k in (f"{style}/{cat}/{coat}/{layer}", f"{style}/{cat}/-/{layer}", f"{style}/-/-/{layer}"):
                if k in packed:
                    return "&" + cname(k)
            return "nullptr"
        f.write(f"const CatImg* const CAT_TABLE[{len(STYLES)}][{len(CATS)}][{len(COATS)}][{len(LAYERS)}] = {{\n")
        for style in STYLES:
            f.write(" {\n")
            for cat in CATS:
                f.write("  {\n")
                for coat in COATS:
                    if style == "8bit":
                        items = [lookup(style, "-", "-", l) for l in LAYERS]
                    else:
                        items = [lookup(style, cat, coat, l) for l in LAYERS]
                    f.write("   {" + ", ".join(items) + "},\n")
                f.write("  },\n")
            f.write(" },\n")
        f.write("};\n")

    with open(os.path.join(SRC, "cat_assets.h"), "w") as f:
        f.write("// AUTO-GENERATED by tools/make_cats.py --export. Do not edit.\n#pragma once\n#include <stdint.h>\n\n")
        f.write("// One layer of the cat area (240 x 200, top-left at screen y=CAT_Y).\n")
        f.write("// Pixels are run-length (count, index) pairs per row; index 0 is transparent.\n")
        f.write("struct CatImg {\n  int16_t x, y;      // top-left in the cat area, screen px\n"
                "  uint16_t w, h;     // stored size (drawn at w*scale x h*scale)\n  uint8_t scale;\n"
                "  const uint16_t* pal;  // RGB565\n  const uint8_t* alpha;\n  const uint32_t* rows;  // byte offset of each row in data\n"
                "  const uint8_t* data;\n};\n\n")
        f.write("enum CatStyle : uint8_t { " + ", ".join(f"STYLE_{s.upper().replace('8BIT', 'EIGHTBIT')}" for s in STYLES) + " };\n")
        f.write("enum CatKind : uint8_t { " + ", ".join(f"CAT_{c.upper()}" for c in CATS) + " };\n")
        f.write("enum CatCoat : uint8_t { " + ", ".join(f"COAT_{c.upper()}" for c in COATS) + " };\n")
        f.write("enum CatLayer : uint8_t { " + ", ".join(f"L_{l.upper()}" for l in LAYERS) + ", L_COUNT };\n\n")
        f.write(f"extern const CatImg* const CAT_TABLE[{len(STYLES)}][{len(CATS)}][{len(COATS)}][{len(LAYERS)}];\n")
        f.write("static const char* const STYLE_NAMES[] = {" + ", ".join(f'"{s}"' for s in STYLES) + "};\n")
        f.write("static const char* const CAT_NAMES[] = {" + ", ".join(f'"{c}"' for c in CATS) + "};\n")
        f.write("static const char* const COAT_NAMES[] = {" + ", ".join(f'"{c}"' for c in COATS) + "};\n")

    # previews for the phone config page (idle pose on a soft background)
    os.makedirs(PREV, exist_ok=True)
    for style in STYLES:
        for cat in (CATS if style != "8bit" else ["-"]):
            for coat in (COATS if style != "8bit" else ["-"]):
                im = compose(layers, style, cat, coat, bg=(214, 232, 248))
                name = f"{style}_{cat}_{coat}.png" if style != "8bit" else "8bit.png"
                im.convert("RGB").save(os.path.join(PREV, name))
    print("previews ->", PREV)
