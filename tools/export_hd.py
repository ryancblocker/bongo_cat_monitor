"""Pack the HD pixel cat (tools/pixelcat.py) + the original 8-bit cat for the firmware,
and write coat previews for the phone page."""
import glob, os, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from sprites import pack, load_8bit, EIGHT  # palette + run-length packing
import pixelcat as pc

ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "firmware", "src")
PREV = os.path.join(ROOT, "bongo-cat-electron", "renderer", "cats")
STYLES = ["hd", "8bit"]
OY = -30        # screen y of sprite row 0, relative to CAT_Y (ear tips land ~26 px into the cat area)
HERO_OY = 268 - 120 - 2 * 119  # landing pose's feet (HD row 119) stand on the ground at screen y 268
ZZZ_DROP = 0    # the HD Zzz are placed by pixelcat.zzz(); the 8-bit ones keep the original spot


def cname(k):
    return "img_" + k.replace("/", "_").replace("-", "x")


def export(L, compose):
    layers = dict(L)
    for name, rel in EIGHT.items():
        layers[f"8bit/-/{name}"] = load_8bit(rel)
    packed, total = {}, 0
    for key, img in layers.items():
        style = key.split("/")[0]
        p = pack(img, 2 if style == "hd" else 4)
        if not p:
            continue
        name = key.split("/")[-1]
        if name.startswith("hero_"):
            # full-body poses: centred, the landing pose's feet on the ground line (see HERO_OY)
            p["sx"] = p["x"] * 2 - 8
            p["sy"] = HERO_OY + p["y"] * 2
        else:
            p["sx"] = p["x"] * p["scale"]
            p["sy"] = OY + p["y"] * p["scale"] + (28 if style == "8bit" and name.startswith("fx_zzz") else 0)
        packed[key] = p
        total += len(p["data"]) + 4 * len(p["rows"]) + 3 * len(p["pal565"])
    print("cat assets: %d images, %.0f KB" % (len(packed), total / 1024))

    with open(os.path.join(SRC, "cat_assets.cpp"), "w") as f:
        f.write("// AUTO-GENERATED by tools/pixelcat.py --export. Do not edit.\n#include \"cat_assets.h\"\n\n")
        for key, p in packed.items():
            n = cname(key)
            f.write(f"// {key}\nstatic const uint16_t {n}_pal[] = {{{','.join(map(str, p['pal565']))}}};\n")
            f.write(f"static const uint8_t {n}_a[] = {{{','.join(map(str, p['alpha']))}}};\n")
            f.write(f"static const uint32_t {n}_rows[] = {{{','.join(map(str, p['rows']))}}};\n")
            f.write(f"static const uint8_t {n}_d[] = {{{','.join(map(str, p['data']))}}};\n")
            f.write(f"static const CatImg {n} = {{{p['sx']}, {p['sy']}, {p['w']}, {p['h']}, {p['scale']}, {n}_pal, {n}_a, {n}_rows, {n}_d}};\n\n")

        def look(style, coat, layer):
            if layer.startswith("hero_"):  # the 8-bit cat borrows the white HD poses
                k = f"hd/{coat if style == 'hd' else 'white'}/{layer}"
                return "&" + cname(k) if k in packed else "nullptr"
            if style == "8bit":
                # the original has no glance/yawn/heart frames: fall back to close ones
                layer = {"face_look_l": "face_stock", "face_look_r": "face_stock", "face_yawn": "face_sleepy", "face_yawn_half": "face_sleepy"}.get(layer, layer)
                k = f"8bit/-/{layer}"
            else:
                k = f"hd/{coat}/{layer}" if f"hd/{coat}/{layer}" in packed else f"hd/-/{layer}"
            return "&" + cname(k) if k in packed else "nullptr"
        f.write(f"const CatImg* const CAT_TABLE[{len(STYLES)}][{len(pc.COATS)}][{len(pc.LAYERS)}] = {{\n")
        for style in STYLES:
            f.write(" {\n")
            for coat in pc.COATS:
                f.write("  {" + ", ".join(look(style, coat, l) for l in pc.LAYERS) + "},\n")
            f.write(" },\n")
        f.write("};\n")

    with open(os.path.join(SRC, "cat_assets.h"), "w") as f:
        f.write("// AUTO-GENERATED by tools/pixelcat.py --export. Do not edit.\n#pragma once\n#include <stdint.h>\n\n")
        f.write("// One layer of the cat (top-left relative to the cat area at screen y=CAT_Y).\n")
        f.write("// Pixels are run-length (count, index) pairs per row; index 0 is transparent.\n")
        f.write("struct CatImg {\n  int16_t x, y;\n  uint16_t w, h;\n  uint8_t scale;\n  const uint16_t* pal;\n"
                "  const uint8_t* alpha;\n  const uint32_t* rows;\n  const uint8_t* data;\n};\n\n")
        f.write("enum CatStyle : uint8_t { STYLE_HD, STYLE_EIGHTBIT };\n")
        f.write("enum CatCoat : uint8_t { " + ", ".join(f"COAT_{c.upper()}" for c in pc.COATS) + ", COAT_COUNT };\n")
        f.write("enum CatLayer : uint8_t { " + ", ".join(f"L_{l.upper()}" for l in pc.LAYERS) + ", L_COUNT };\n\n")
        f.write(f"extern const CatImg* const CAT_TABLE[{len(STYLES)}][{len(pc.COATS)}][{len(pc.LAYERS)}];\n")
        f.write("static const char* const STYLE_NAMES[] = {" + ", ".join(f'"{s}"' for s in STYLES) + "};\n")
        f.write("static const char* const COAT_NAMES[] = {" + ", ".join(f'"{c}"' for c in pc.COATS) + "};\n")

    # phone previews: idle cat, cropped to the part the screen shows
    for old in glob.glob(os.path.join(PREV, "*.png")):
        os.remove(old)
    os.makedirs(PREV, exist_ok=True)
    def save(im, name):
        im = im.crop((0, 40, 512, 440)).resize((256, 200), Image.NEAREST)
        im.convert("RGB").save(os.path.join(PREV, name))
    for coat in pc.COATS:
        save(compose(L, coat, bg=(176, 204, 232)), f"hd_{coat}.png")
    eight = Image.new("RGBA", (64, 64), (176, 204, 232, 255))
    for n in ("body", "face_stock", "desk", "paws_up"):
        eight.alpha_composite(layers[f"8bit/-/{n}"])
    save(eight.resize((512, 512), Image.NEAREST), "8bit.png")
    print("previews ->", PREV)
